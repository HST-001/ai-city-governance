// 3. 合并数据函数
function mergeAddressData(existingData, newData) {
  console.log('开始合并地址数据...');
  
  return existingData.map(province => {
    // 检查是否有新数据
    if (newData[province.label]) {
      const provinceNewData = newData[province.label];
      
      // 合并城市数据
      const updatedCities = province.children.map(city => {
        // 直辖市和特别行政区
        if (provinceNewData.cities[province.label] && provinceNewData.cities[province.label].districts[city.label]) {
          const districtsNewData = provinceNewData.cities[province.label].districts;
          
          // 如果城市是直辖市的区，则直接添加街道数据
          const streets = districtsNewData[city.label] || [];
          return {
            ...city,
            children: streets.map(street => ({
              value: `${province.value}-${city.value.split('-')[1]}-${street.toLowerCase().replace(/\s+/g, '-')}`,
              label: street,
              children: []
            }))
          };
        } 
        // 普通城市
        else if (provinceNewData.cities[city.label]) {
          const cityNewData = provinceNewData.cities[city.label];
          
          // 合并区县数据
          const updatedDistricts = city.children.map(district => {
            const streets = cityNewData.districts[district.label] || [];
            return {
              ...district,
              children: streets.map(street => ({
                value: `${province.value}-${city.value.split('-')[1]}-${district.value.split('-')[2]}-${street.toLowerCase().replace(/\s+/g, '-')}`,
                label: street,
                children: []
              }))
            };
          });
          
          return {
            ...city,
            children: updatedDistricts
          };
        }
        
        return city;
      });
      
      return {
        ...province,
        children: updatedCities
      };
    }
    
    return province;
  });
}

